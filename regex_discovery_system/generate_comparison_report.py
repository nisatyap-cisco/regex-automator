#!/usr/bin/env python3
"""Generate an HTML comparison report: user ('mine') regex vs new researcher regex.

Reads regex_comparison.json for user patterns and *_regex_patterns.json for
researcher patterns, then produces comparison_report_new.html with per-condition
analysis generated by Bedrock Claude.
"""

import html
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from utils.bedrock_client import invoke_claude, load_config
from utils.paths import slugify

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
COMPARISON_FILE = os.path.join(SCRIPT_DIR, "regex_comparison.json")
RESEARCHER_FILE = os.path.join(os.path.dirname(SCRIPT_DIR), "researcher_regex_export.json")
RESULTS_DIR = os.path.join(SCRIPT_DIR, "results")
OUTPUT_HTML = os.path.join(RESULTS_DIR, "coverage_report.html")

ANALYSIS_PROMPT = """You are a regex comparison analyst.  Given:
- CONDITION: {condition}
- USER REGEX ("mine"):  {mine_regex}
- RESEARCHER REGEX:     {researcher_regex}

Produce a JSON object (no markdown fences) with these fields:
{{
  "coverage_pct": <integer 0-100>,
  "badges": ["<badge text>", ...],
  "conditions": [
    {{"name": "<condition name>", "status": "tick|cross|warn|plus", "notes": "<one-line note>"}},
    ...
  ],
  "note": "<one-line summary note>"
}}

Rules for analysis:
- coverage_pct = what % of the researcher's structural conditions does "mine" satisfy.
- "tick" = condition fully met, "cross" = missing, "warn" = partially met, "plus" = mine is stricter (bonus).
- Be specific about structural differences: separators, character classes, alternation branches, length.
- If mine is stricter on a dimension (e.g. restricts to valid ranges), that's a "plus" bonus.
- If researcher handles optional separators (space/hyphen) that mine doesn't, mark as "cross" or "warn".
- Return ONLY valid JSON."""


def load_entries() -> list[dict]:
    with open(COMPARISON_FILE) as f:
        mine_entries = json.load(f)

    # Build slug → researcher_regex from researcher_regex_export.json
    researcher_map = {}
    if os.path.exists(RESEARCHER_FILE):
        with open(RESEARCHER_FILE) as f:
            researcher_entries = json.load(f)
        for e in researcher_entries:
            slug = e.get("slug", "")
            rx = e.get("researcher_regex")
            if slug and rx:
                researcher_map[slug] = rx

    # Merge researcher regex into each mine entry
    for e in mine_entries:
        slug = e.get("slug", "")
        e["_researcher"] = researcher_map.get(slug)

    return mine_entries


def get_researcher_regex(entry: dict) -> "str | None":
    """Get researcher regex from the merged entry."""
    return entry.get("_researcher")


def strip_wb(regex_str: str) -> str:
    """Strip \\b word boundaries for display comparison."""
    r = regex_str
    if r.startswith("\\b"):
        r = r[2:]
    if r.endswith("\\b"):
        r = r[:-2]
    return r


def analyze_pair(condition: str, mine: str, researcher: str, config: dict) -> dict:
    """Use LLM to produce structured comparison."""
    prompt = ANALYSIS_PROMPT.format(
        condition=condition,
        mine_regex=mine,
        researcher_regex=researcher,
    )
    raw = invoke_claude(prompt, config)
    raw = raw.strip()
    if raw.startswith("```"):
        lines = raw.splitlines()
        lines = [l for l in lines if not l.strip().startswith("```")]
        raw = "\n".join(lines).strip()
    try:
        return json.loads(raw)
    except json.JSONDecodeError:
        return {
            "coverage_pct": 50,
            "badges": [],
            "conditions": [{"name": "Parse error", "status": "warn", "notes": "LLM response was not valid JSON"}],
            "note": f"Raw: {raw[:200]}",
        }


def _esc(text: str) -> str:
    return html.escape(text, quote=True)


def _badge_class(pct: int) -> str:
    if pct >= 75:
        return "badge-high"
    if pct >= 40:
        return "badge-mid"
    return "badge-low"


def _status_span(status: str) -> str:
    mapping = {
        "tick": '<span class="tick">✓</span>',
        "cross": '<span class="cross">✗</span>',
        "warn": '<span class="warn">~</span>',
        "plus": '<span class="plus">+1</span>',
    }
    return mapping.get(status, status)


def build_html(entries: list[dict], analyses: dict[str, dict]) -> str:
    """Build the full HTML report."""

    high = sum(1 for a in analyses.values() if a.get("coverage_pct", 0) >= 75)
    mid = sum(1 for a in analyses.values() if 40 <= a.get("coverage_pct", 0) < 75)
    low = sum(1 for a in analyses.values() if a.get("coverage_pct", 0) < 40)
    total = len(analyses)
    avg_cov = round(sum(a.get("coverage_pct", 0) for a in analyses.values()) / max(total, 1))

    entry_blocks: list[str] = []
    for i, entry in enumerate(entries, 1):
        slug = entry["slug"]
        mine_display = strip_wb(entry["mine"])
        analysis = analyses.get(slug)
        if analysis is None:
            continue
        researcher_display = strip_wb(analysis.get("_researcher_regex", "N/A"))
        pct = analysis.get("coverage_pct", 0)
        badges_html = f'<span class="badge {_badge_class(pct)}">{pct}% coverage</span>'
        for b in analysis.get("badges", []):
            badges_html += f' <span class="badge badge-better">{_esc(b)}</span>'

        rows = ""
        for c in analysis.get("conditions", []):
            rows += (
                f'<tr><td>{_esc(c["name"])}</td>'
                f'<td>{_status_span(c["status"])}</td>'
                f'<td>{c["notes"]}</td></tr>\n'
            )

        note = _esc(analysis.get("note", ""))

        block = f"""
  <div class="entry">
    <div class="entry-header">
      <div class="entry-title">{i}. {_esc(entry["condition"].title())}</div>
      {badges_html}
    </div>
    <div class="regexes">
      <div class="regex-col"><div class="regex-label">Mine</div><div class="regex-val">{_esc(mine_display)}</div></div>
      <div class="regex-col"><div class="regex-label">Researcher (new)</div><div class="regex-val">{_esc(researcher_display)}</div></div>
    </div>
    <table class="cond-table">
      <tr><th>Condition</th><th>Status</th><th>Notes</th></tr>
      {rows}
    </table>
    <div class="note"><span>Summary:</span> {note}</div>
  </div>
"""
        entry_blocks.append(block)

    entries_html = "\n".join(entry_blocks)

