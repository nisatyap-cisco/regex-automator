def main() -> None:
    config = load_config(os.path.join(SCRIPT_DIR, "config.yaml"))
    entries = load_entries()
    print(f"Loaded {len(entries)} conditions")

    analyses: dict[str, dict] = {}

    for i, entry in enumerate(entries, 1):
        slug = entry["slug"]
        condition = entry["condition"]
        mine = entry["mine"]
        researcher = get_researcher_regex(entry)

        if not researcher:
            print(f"  [{i}] {condition}: NO RESEARCHER REGEX — skipping")
            continue

        if "java" in slug:
            print(f"  [{i}] {condition}: skipping java")
            continue

        print(f"  [{i}] Analyzing: {condition}")
        analysis = analyze_pair(condition, mine, researcher, config)
        analysis["_researcher_regex"] = researcher
        analyses[slug] = analysis

    report_html = build_html(entries, analyses)
    with open(OUTPUT_HTML, "w", encoding="utf-8") as f:
        f.write(report_html)
    print(f"\nReport written to {OUTPUT_HTML}")


if __name__ == "__main__":
    main()
